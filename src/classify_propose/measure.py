"""Measure Classify & Propose against NFR-PERF-01 (docs/requirements.md):
classification completes within 5 s of intake, p95 over 20 seeded reports.

    python -m src.classify_propose.measure            # print the result
    python -m src.classify_propose.measure --write    # also write docs/measurements.md

The method is the requirement's own: 20 seeded reports, time each from intake
to the severity tag, take the 95th percentile. The model is whatever
CLASSIFY_MODEL selects (the fake one by default), so the number is only as
meaningful as that model. The same run also records the confidence spread and
how many reports a person would be asked to look at, because ADR 0001 says to
revisit the model if more than 40% of reports route to human review.
"""
import glob
import math
import sqlite3
import sys
import tempfile
import time
from datetime import UTC, datetime
from pathlib import Path

from src.classify_propose.model import get_model
from src.classify_propose.service import classify_and_propose
from src.decide_proposal.service import needs_human
from src.intake_gateway.service import submit_report

LIMIT_SECONDS = 5.0
HUMAN_REVIEW_REVISIT_SHARE = 0.40

# Twenty seeded reports: clear medical cases, hard ones, and vague ones.
SEED_REPORTS = [
    "person fell, visible leg injury, conscious and talking",
    "man collapsed, chest pain, not breathing well",
    "child fell from a bike, bleeding from the knee",
    "woman unconscious on the sidewalk",
    "driver hurt after a crash, pain in the neck",
    "elderly man dizzy, chest pain, conscious",
    "worker injured by falling equipment, bleeding",
    "teenager not breathing after swimming",
    "bystander hurt in a fall on the stairs",
    "cyclist injured, conscious and talking, arm injury",
    "someone is bleeding badly near the loading dock",
    "pain in the chest, started ten minutes ago",
    "man fell off a ladder, injury to the back",
    "woman fainted, now conscious, no visible injury",
    "child hurt at the playground, crying, leg pain",
    "driver unconscious, car in a ditch",
    "something happened, not sure how bad",
    "no one is answering, possible trouble",
    "a person is lying there, cannot tell",
    "reported by a neighbour, details unknown",
]


def percentile(values, fraction):
    """Nearest-rank percentile."""
    ordered = sorted(values)
    rank = max(1, math.ceil(fraction * len(ordered)))
    return ordered[rank - 1]


def measure(model=None, texts=None):
    model = model or get_model()
    texts = texts or SEED_REPORTS
    with tempfile.TemporaryDirectory() as tmp:
        conn = sqlite3.connect(Path(tmp) / "measure.sqlite")
        conn.row_factory = sqlite3.Row
        for path in sorted(glob.glob("migrations/*.sql")):
            with open(path, encoding="utf-8") as f:
                conn.executescript(f.read())
        with open("seed/iteration-1.sql", encoding="utf-8") as f:
            conn.executescript(f.read())

        seconds, confidences, human = [], [], 0
        for i, text in enumerate(texts):
            report = submit_report(
                conn,
                1,
                {
                    "location": f"seed location {i}",
                    "severity_raw": text,
                    "timestamp_reported": "2026-11-01T12:00:00+00:00",
                    "reporting_unit": "measure",
                },
            )
            start = time.perf_counter()
            result = classify_and_propose(conn, report["report_id"], model)
            seconds.append(time.perf_counter() - start)
            confidences.append(result["confidence"])
            human += needs_human(result["confidence"], result["severity"])
        conn.close()

    p95 = percentile(seconds, 0.95)
    return {
        "model": f"{model.identifier} v{model.version}",
        "reports": len(texts),
        "p50_seconds": percentile(seconds, 0.50),
        "p95_seconds": p95,
        "max_seconds": max(seconds),
        "within_limit": p95 <= LIMIT_SECONDS,
        "confidence_min": min(confidences),
        "confidence_mean": sum(confidences) / len(confidences),
        "confidence_max": max(confidences),
        "under_75": sum(c < 75 for c in confidences),
        "human_review_share": human / len(texts),
    }


def render(r):
    verdict = "PASS" if r["within_limit"] else "FAIL"
    share = r["human_review_share"]
    revisit = "over" if share > HUMAN_REVIEW_REVISIT_SHARE else "at or under"
    return f"""# Measurements

Generated by `python -m src.classify_propose.measure --write` on {datetime.now(UTC).date().isoformat()}.

## NFR-PERF-01: report classification within 5 s (p95, 20 seeded reports)

Requirement (`docs/requirements.md`): classification completes within 5 seconds of intake, p95 over 20 seeded reports, on the target hardware (24 GB GPU, local model). Method: submit each of the 20 seeded reports (in `src/classify_propose/measure.py`), time each call from intake to the severity tag, take the 95th percentile (nearest rank).

| Measure | Result |
|---|---|
| Model measured | `{r["model"]}` |
| Reports | {r["reports"]} |
| p50 | {r["p50_seconds"] * 1000:.2f} ms |
| **p95** | **{r["p95_seconds"] * 1000:.2f} ms** ({verdict} against the 5000 ms limit) |
| Slowest | {r["max_seconds"] * 1000:.2f} ms |

**What this does and does not show.** The model measured is the rules-based fake, which answers instantly, so this proves the measuring method and the classification path around the model, not the speed of a real language model. The requirement is not met until the same command is run with the real model (Ollama) on the target machine. Nothing here says the real model will be fast enough.

## Confidence spread (ADR 0001 revisit trigger)

ADR 0001 says to re-evaluate the model if more than 40% of reports route to human review.

| Measure | Result |
|---|---|
| Lowest / mean / highest confidence | {r["confidence_min"]} / {r["confidence_mean"]:.1f} / {r["confidence_max"]} |
| Reports under 75 | {r["under_75"]} of {r["reports"]} |
| Share a person would be asked to review (confidence under 75, or Severe/Critical) | {share:.0%} ({revisit} the 40% line) |

The share depends heavily on how the seeded set was written (four of the twenty are deliberately vague, and several clear cases come out Severe), so it describes the fake model on this set, not what real traffic would do.
"""


def main():
    result = measure()
    text = render(result)
    print(text)
    if "--write" in sys.argv:
        Path("docs/measurements.md").write_text(text, encoding="utf-8")
        print("wrote docs/measurements.md")


if __name__ == "__main__":
    main()
